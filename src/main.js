import { collectNewOrderTicket, copyTicketForClient } from './features/ticket.js';
import { startClock } from './ui/clock.js';

document.addEventListener('DOMContentLoaded',()=>{
  startClock();
  setupScreen();
  initNav();
  initChangeExcel();
  initPayToggle();
  initCategoryBtns();
  initMenuSearch();
  initOrdersFilter();
  initOrderDetailModal();
  initAddProductModal();
  initAddCategoryModal();
  initClienteAutocomplete();
  initAjuste();
  renderMenuGrid();
  renderMenuEditor();
  initDashboardFilter();
  initClientsTab();
  initBATab();
  initInventoryTab();
  document.getElementById('btn-guardar-orden').addEventListener('click',saveOrder);
  document.getElementById('btn-copiar-ticket')?.addEventListener('click',()=>copyTicketForClient(collectNewOrderTicket()));
  document.getElementById('btn-limpiar-orden').addEventListener('click',clearForm);
  stampNewOrderWhen();
  initLiveOrderWhen();
  if('serviceWorker' in navigator) navigator.serviceWorker.register('sw.js').catch(()=>{});
  if(/[?&]test=1(?:&|$)/.test(location.search)) runInventorySelfTest();
});
